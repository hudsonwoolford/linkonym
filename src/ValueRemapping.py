def BezierApproximation(t: float):
    t = min(1, t)
    t = max(0, t)

    for i in range(1, len(xValues)):
        if(xValues[i-1] <= t and xValues[i] >= t):
            upper = xValues[i] if xValues[i] != 0 else 1
            upperWeight = (t-xValues[i-1]) / (upper-xValues[i-1])
            return (yValues[i-1] * (1-upperWeight) + yValues[i] * upperWeight)
    return 0

